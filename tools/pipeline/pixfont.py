_BOX = "#####|#...#|#...#|#...#|#...#|#...#|#####"


def _glyph(ch: str) -> list[str]:
    return _ROWS.get(ch.upper(), _BOX).split("|")


def text_width(text: str, scale: int = 1) -> int:
    return (len(text) * ADVANCE - 1) * scale if text else 0


def draw_text(img: Image, x: int, y: int, text: str, colour: tuple[int, int, int, int],
              scale: int = 1) -> None:
    """Draw text with its top-left at (x, y); pixels outside the image are skipped."""
    for i, ch in enumerate(text):
        rows = _glyph(ch)
        gx = x + i * ADVANCE * scale
        for ry, row in enumerate(rows):
            for rx, bit in enumerate(row):
                if bit != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        px, py = gx + rx * scale + sx, y + ry * scale + sy
                        if 0 <= px < img.width and 0 <= py < img.height:
                            img.put(px, py, colour)
