BEHIND = set('.')                    # paint only where nothing is drawn yet (the cape and collar sit behind)

def cape(s, f, outline, folds, only=None):
    """Cape: shadow red base, then each fold a tapering lit band (lit side left), 3+ px wide below the blades."""
    part(s, f, outline, CA, [0.8], ky=0.2, only=only)
    for fo in folds:
        part(s, f, fo, ['s', 's', 'r'], [0.2, -0.3], ky=0.1, only=only)

